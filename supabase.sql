-- Ejecutar una sola vez en Supabase > SQL Editor > New query.
create table if not exists public.room_events (
  id bigint generated by default as identity primary key,
  room_code text not null,
  event_type text not null check (event_type in ('join','reaction','danger')),
  participant_id text,
  name text,
  avatar text,
  emoji text,
  label text,
  created_at timestamptz not null default now()
);

create index if not exists room_events_room_created_idx
  on public.room_events (room_code, created_at desc);

alter table public.room_events enable row level security;

grant select, insert on public.room_events to anon, authenticated;
grant usage, select on sequence public.room_events_id_seq to anon, authenticated;

drop policy if exists "room events are readable" on public.room_events;
create policy "room events are readable"
  on public.room_events for select to anon, authenticated
  using (room_code = 'POMELO-PAGOTIC');

drop policy if exists "room events can be added" on public.room_events;
create policy "room events can be added"
  on public.room_events for insert to anon, authenticated
  with check (
    room_code = 'POMELO-PAGOTIC'
    and event_type in ('join','reaction','danger')
  );

-- Habilitar cambios en tiempo real para esta tabla.
alter publication supabase_realtime add table public.room_events;
